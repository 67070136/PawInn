-- Room owner: room types and physical rooms in the shared pawinn database.
BEGIN;

CREATE TABLE IF NOT EXISTS room_types (
    room_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    description TEXT,
    species VARCHAR(10) NOT NULL CHECK (species IN ('Dog', 'Cat')),
    price_per_night NUMERIC(10,2) NOT NULL CHECK (price_per_night > 0)
);

CREATE TABLE IF NOT EXISTS rooms (
    room_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_type_id INTEGER NOT NULL REFERENCES room_types(room_type_id) ON DELETE RESTRICT,
    room_number VARCHAR(10) NOT NULL UNIQUE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

COMMIT;
