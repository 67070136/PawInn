-- Booking owner: load account and room schemas before this file.
BEGIN;
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
    pet_id INTEGER NOT NULL,
    room_id INTEGER NOT NULL REFERENCES rooms(room_id) ON DELETE RESTRICT,
    check_in_date DATE NOT NULL,
    check_out_date DATE NOT NULL,
    nightly_rate NUMERIC(10,2) NOT NULL CHECK (nightly_rate > 0),
    total_price NUMERIC(10,2) NOT NULL CHECK (total_price > 0),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CONFIRMED', 'CANCELLED', 'COMPLETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    payment_status VARCHAR(10) NOT NULL DEFAULT 'UNPAID'
        CHECK (payment_status IN ('UNPAID', 'SUCCESS', 'FAILED')),
    payment_reference VARCHAR(100) UNIQUE,
    paid_at TIMESTAMPTZ,
    refund_status VARCHAR(15) NOT NULL DEFAULT 'NOT_REQUESTED'
        CHECK (refund_status IN ('NOT_REQUESTED', 'PENDING', 'SUCCESS', 'FAILED')),
    refund_amount NUMERIC(10,2) CHECK (refund_amount >= 0 AND refund_amount <= total_price),
    refund_reference VARCHAR(100) UNIQUE,
    refunded_at TIMESTAMPTZ,

    FOREIGN KEY (pet_id, user_id) REFERENCES pets(pet_id, owner_id) ON DELETE RESTRICT,
    CHECK (check_out_date > check_in_date),
    CHECK (total_price = nightly_rate * (check_out_date - check_in_date)),
    CHECK (status NOT IN ('CONFIRMED', 'COMPLETED') OR payment_status = 'SUCCESS'),
    CHECK (payment_status <> 'SUCCESS' OR (payment_reference IS NOT NULL AND paid_at IS NOT NULL)),
    CHECK (refund_status = 'NOT_REQUESTED' OR payment_status = 'SUCCESS'),
    CHECK (refund_status <> 'SUCCESS' OR (
        refund_amount IS NOT NULL AND refund_amount = total_price
        AND refund_reference IS NOT NULL AND refunded_at IS NOT NULL
    )),

    -- Check-out is exclusive: adjacent stays are allowed.
    -- These constraints also reject conflicting simultaneous inserts.
    CONSTRAINT bookings_no_room_overlap EXCLUDE USING gist (
        room_id WITH =, daterange(check_in_date, check_out_date, '[)') WITH &&
    ) WHERE (status IN ('PENDING', 'CONFIRMED')),
    CONSTRAINT bookings_no_pet_overlap EXCLUDE USING gist (
        pet_id WITH =, daterange(check_in_date, check_out_date, '[)') WITH &&
    ) WHERE (status IN ('PENDING', 'CONFIRMED'))
);

CREATE TABLE IF NOT EXISTS cancellation_requests (
    cancellation_request_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    reason TEXT NOT NULL CHECK (length(trim(reason)) > 0),
    status VARCHAR(10) NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'APPROVED', 'DECLINED')),
    requested_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    reviewed_by INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,
    reviewed_at TIMESTAMPTZ,
    review_notes TEXT,
    CHECK (
        (status = 'PENDING' AND reviewed_by IS NULL AND reviewed_at IS NULL)
        OR (status IN ('APPROVED', 'DECLINED') AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS one_pending_cancellation_per_booking
    ON cancellation_requests (booking_id) WHERE status = 'PENDING';

CREATE TABLE IF NOT EXISTS booking_logs (
    log_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id INTEGER NOT NULL REFERENCES bookings(booking_id) ON DELETE RESTRICT,
    actor_user_id INTEGER REFERENCES users(user_id) ON DELETE RESTRICT,
    action VARCHAR(80) NOT NULL,
    details TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS bookings_user_created ON bookings (user_id, created_at);
COMMIT;
